#ifndef EXECUTION_MODES_H
#define EXECUTION_MODES_H

#include "BenchmarkConfig.h"
#include <cmath>
#include <vector>

inline std::vector<ExecutionMode> enabled_modes(const BenchmarkConfig& config) {
    std::vector<ExecutionMode> modes;
    if (config.generate_multiseq) modes.push_back(ExecutionMode::MULTISEQUENTIAL);
    return modes;
}

inline const char* mode_directory([[maybe_unused]] ExecutionMode mode) {
    return "multisequential";
}


inline bool same_point(const BenchmarkResult& result, double ratio_pct, int pause, ExecutionMode mode) {
    return std::abs(result.ratio_pct - ratio_pct) < 1e-9 && result.pause == pause && result.mode == mode;
}

#endif
